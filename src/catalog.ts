export const CATALOG_BY_ID: Record<string, CatalogItem> = Object.fromEntries(
  CATALOG.map((entry) => [entry.id, entry]),
)

export function itemsInCategory(category: AssetCategory): CatalogItem[] {
  return CATALOG.filter((item) => item.category === category)
}

export function searchCatalog(query: string): CatalogItem[] {
  const needle = query.trim().toLowerCase()
  if (!needle) return CATALOG
  return CATALOG.filter((item) => {
    const haystack = `${item.name} ${item.description} ${item.category} ${item.kind}`.toLowerCase()
    return haystack.includes(needle)
  })
}
